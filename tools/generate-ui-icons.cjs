#!/usr/bin/env node
// Generates src/ui/iconNodes.js from Tabler Icons' outline node data.
//
// Why a generated subset instead of a dependency: the approved design board
// draws every icon with Tabler Icons 3.19.0 (MIT). Shipping the full webfont
// adds ~5000 glyphs we never use, and @tabler/icons-react-native pulls a
// second copy of the node data at runtime. react-native-svg is already a
// dependency, so we render only the ~120 icons listed in tools/ui-icons.txt.
//
// Usage: node tools/generate-ui-icons.cjs <path>/tabler-nodes-outline.json
// (get it with `npm pack @tabler/icons@3.19.0` and extract the tarball).
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const source = process.argv[2];
if (!source) {
  console.error('usage: node tools/generate-ui-icons.cjs <tabler-nodes-outline.json>');
  process.exit(2);
}

const nodes = JSON.parse(fs.readFileSync(source, 'utf8'));
const names = fs.readFileSync(path.join(root, 'tools', 'ui-icons.txt'), 'utf8')
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'));

const missing = names.filter((name) => !nodes[name]);
if (missing.length) {
  console.error(`unknown Tabler icon(s): ${missing.join(', ')}`);
  process.exit(1);
}

// Keep only the geometry react-native-svg needs; drop Tabler's
// `stroke="none"` bounding-box path which every icon starts with in the SVG
// files (the node JSON already omits it, the filter is defensive).
const ALLOWED = new Set(['path', 'circle', 'rect']);
const out = {};
for (const name of [...new Set(names)].sort()) {
  out[name] = nodes[name]
    .filter(([tag, attrs]) => ALLOWED.has(tag) && attrs.stroke !== 'none')
    .map(([tag, attrs]) => [tag, attrs]);
}

const body = `// GENERATED by tools/generate-ui-icons.cjs from Tabler Icons 3.19.0 (MIT,
// Copyright (c) 2020-2024 Paweł Kuna). Do not edit by hand: add the name to
// tools/ui-icons.txt and re-run the generator.
export const ICON_NODES = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(root, 'src', 'ui', 'iconNodes.js'), body);
console.log(`wrote ${Object.keys(out).length} icons`);
